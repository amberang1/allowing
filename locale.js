const languageKey = 'allowing-language';
function readLanguage() {
  try { return localStorage.getItem(languageKey) === 'zh-CN' ? 'zh-CN' : 'en'; }
  catch { return 'en'; }
}
let language = readLanguage();
function translate(text) {
  if (language !== 'zh-CN') return text;
  return Object.hasOwn(chinese, text) ? chinese[text] : text;
}

function updateLanguage() {
  const isChinese = language === 'zh-CN';
  document.documentElement.lang = language;
  document.title = isChinese ? document.body.dataset.titleZh : document.body.dataset.titleEn;
  const brand = document.querySelector('.brand');
  brand.setAttribute('aria-label', isChinese ? 'Allowing · 首页' : 'Allowing — home');
  brand.title = isChinese ? '回到首页' : 'Return home';
  document.querySelector('[data-practice-link]').textContent = translate('Practice');
  document.querySelectorAll('[data-language]').forEach(button => {
    button.setAttribute('aria-pressed', String(button.dataset.language === language));
  });
}
function setLanguage(next) {
  if (language === next) return;
  language = next;
  try { localStorage.setItem(languageKey, language); } catch { /* use it for this visit */ }
  updateLanguage();
  document.dispatchEvent(new Event('allowing-language-change'));
}
document.querySelectorAll('[data-language]').forEach(button => {
  button.addEventListener('click', () => setLanguage(button.dataset.language));
});
window.addEventListener('pageshow', () => {
  const saved = readLanguage();
  if (saved !== language) setLanguage(saved);
});
